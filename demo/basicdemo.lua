-- does some extra setup
local http = require"tichttp"

-- basic LTN12 sink for receiving the code
local ltn12 = require"ltn12"
local t = {}
local sink = ltn12.sink.table(t)

-- request the code
assert(http.request{
	url="https://raw.githubusercontent.com/MineRobber9000/tic80-luahttp/refs/heads/trunk/demo/basicdemo_code.lua",
	sink=sink,
	verify="peer" -- tichttp sets up the certificate authority stuff for this to work
})

-- run the code
local code = table.concat(t)
assert(load(code))()
